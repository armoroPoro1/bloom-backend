import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';
import { loadConfig } from '../src/config.js';
import { createDatabase, migrate } from '../src/core/db.js';
import { buildApp } from '../src/app.js';
const config = loadConfig({
  NODE_ENV: 'test',
  DATABASE_DRIVER: 'pglite',
  PGLITE_DIR: 'memory://',
  LOG_LEVEL: 'silent',
});
const db = await createDatabase(config);
let app: Awaited<ReturnType<typeof buildApp>> | undefined;
try {
  await migrate(db);
  app = await buildApp({ db, config });
  const document = app.swagger();
  const methods = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'] as const;
  type Operation = {
    tags?: string[];
    summary?: string;
    security?: Record<string, string[]>[];
  };
  const paths = document.paths as Record<
    string,
    Partial<Record<(typeof methods)[number], Operation>>
  >;
  const operations = Object.entries(paths).flatMap(([path, item]) =>
    methods.flatMap((method, methodOrder) => {
      const operation = item[method];
      if (!operation) return [];
      const security = operation.security ?? document.security ?? [];
      return [
        {
          path,
          method: method.toUpperCase(),
          methodOrder,
          tag: operation.tags?.[0] ?? 'Other',
          summary: operation.summary ?? '',
          auth:
            security.length > 0 && security.every((requirement) => Object.keys(requirement).length)
              ? 'Required'
              : 'Public / optional',
        },
      ];
    }),
  );
  operations.sort((a, b) => a.path.localeCompare(b.path, 'en') || a.methodOrder - b.methodOrder);
  const escapeCell = (value: string) => value.replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
  const index = [
    '# API endpoint index',
    '',
    `Generated by \`npm run openapi\` from \`openapi.json\` for release ${document.info.version}. Do not edit this file manually. All methods below are implemented route registrations. Use \`/docs/\` at runtime for request schemas. Authentication is Bearer; an authenticated role may also be required. The table indicates whether a token is required, while the module guides specify ownership and role details.`,
    '',
    `**${operations.length} operations across ${new Set(operations.map((operation) => operation.path)).size} paths.**`,
    '',
    ...[...new Set(operations.map((operation) => operation.tag))]
      .sort()
      .flatMap((tag) => [
        `## ${escapeCell(tag)}`,
        '',
        '| Method | Path | Auth | Purpose |',
        '| --- | --- | --- | --- |',
        ...operations
          .filter((operation) => operation.tag === tag)
          .map(
            (operation) =>
              `| ${operation.method} | \`${escapeCell(operation.path)}\` | ${operation.auth} | ${escapeCell(operation.summary)} |`,
          ),
        '',
      ]),
  ].join('\n');
  const markdown = await format(index, { parser: 'markdown' });
  await mkdir(resolve('docs'), { recursive: true });
  await Promise.all([
    writeFile(resolve('docs/openapi.json'), JSON.stringify(document, null, 2) + '\n'),
    writeFile(resolve('docs/API_INDEX.md'), markdown),
  ]);
  console.log(
    `Exported ${operations.length} API operations to docs/openapi.json and docs/API_INDEX.md`,
  );
} finally {
  try {
    await app?.close();
  } finally {
    await db.close();
  }
}
